#!/usr/bin/env node
// Builds the design system from tokens/tokens.json, with no dependencies:
//
//   dist/tokens.css          custom properties (--al-*): light, dark, and Arabic
//   dist/tailwind-theme.css  a Tailwind v4 @theme mapping onto them
//   dist/tokens.json         every token, flat, resolved, per mode (for JS)
//   dist/arabesque.css       tokens + css/ in cascade layers, one file to link
//   docs/contrast.md         every colour pair the system relies on, measured
//
// It fails (exit 1) if a pair falls below its WCAG minimum.

import { readFileSync, writeFileSync, readdirSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const read = (p) => readFileSync(join(root, p), "utf8");
const write = (p, s) => { mkdirSync(dirname(join(root, p)), { recursive: true }); writeFileSync(join(root, p), s); };
const MODES = "com.arabesquelabs.modes";
const tokens = JSON.parse(read("tokens/tokens.json"));

// ---- collect -----------------------------------------------------------------------------

/** Every token: its path, type (inherited from its groups), value and modes. */
const all = [];
(function walk(node, path, type) {
  const t = node.$type || type;
  if ("$value" in node) {
    all.push({ path, type: t, value: node.$value, modes: node.$extensions?.[MODES] || {}, description: node.$description });
    return;
  }
  for (const [k, v] of Object.entries(node)) if (!k.startsWith("$") && v && typeof v === "object") walk(v, [...path, k], t);
})(tokens, [], undefined);

const byPath = new Map(all.map((t) => [t.path.join("."), t]));
/** A token's custom property: its path without the layer, prefixed. */
const cssName = (t) => `--al-${t.path.slice(1).join("-")}`;
const isRef = (v) => typeof v === "string" && /^\{[^}]+\}$/.test(v);
const target = (v) => {
  const t = byPath.get(v.slice(1, -1));
  if (!t) throw new Error(`no token ${v}`);
  return t;
};

const GENERIC = new Set(["serif", "sans-serif", "monospace", "system-ui", "ui-sans-serif", "ui-serif", "ui-monospace"]);

/** A value as CSS: references become var(), the rest formatted by type. */
function css(t, v) {
  if (isRef(v)) return `var(${cssName(target(v))})`;
  // Family names quoted; generic families (system-ui, serif…) as keywords.
  if (t.type === "fontFamily") return v.map((f) => (GENERIC.has(f) ? f : `"${f}"`)).join(", ");
  if (t.type === "cubicBezier") return `cubic-bezier(${v.join(", ")})`;
  if (t.path[1] === "text") return `calc(${v} * var(--al-script-scale))`;
  return String(v);
}

/** A value fully resolved (for the contrast check and dist/tokens.json). */
function resolve(v, mode) {
  while (isRef(v)) {
    const t = target(v);
    v = (mode && t.modes[mode]) ?? t.value;
  }
  return v;
}

// ---- tokens.css --------------------------------------------------------------------------

const decl = (list, mode) => list.map((t) => `  ${cssName(t)}: ${css(t, mode ? t.modes[mode] : t.value)};`).join("\n");
const base = all.filter((t) => t.path[0] !== "$");
const dark = all.filter((t) => t.modes.dark !== undefined);
const arabic = all.filter((t) => t.modes.ar !== undefined);
const banner = "/* Arabesque Labs design system: tokens. Generated by scripts/build.mjs from tokens/tokens.json: don't edit. */\n";

const tokensCss = `${banner}
:root {
  color-scheme: light;
${decl(base)}
}

/* Dark: by the system's setting, unless light is chosen; or when chosen. */
@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
    color-scheme: dark;
${decl(dark, "dark").replace(/^/gm, "  ")}
  }
}
:root[data-theme="dark"] {
  color-scheme: dark;
${decl(dark, "dark")}
}

/* Arabic: a little larger, more line height, no letter-spacing. The sizes
   are declared again here, so they're worked out with Arabic's scale even
   inside a page in another language (var() resolves where it's declared). */
:lang(ar) {
${decl(arabic, "ar")}
${decl(all.filter((t) => t.path[1] === "text"))}
}
`;
write("dist/tokens.css", tokensCss);

// ---- tailwind-theme.css ------------------------------------------------------------------

const tw = [];
for (const t of all) {
  const [layer, group, ...rest] = t.path;
  if (layer !== "semantic") continue;
  const name = rest.join("-");
  const map = { color: "color", font: "font", text: "text", leading: "leading", weight: "font-weight", tracking: "tracking", radius: "radius", ease: "ease", breakpoint: "breakpoint" }[group];
  if (map) tw.push(`  --${map}-${name}: var(${cssName(t)});`);
}
write("dist/tailwind-theme.css", `/* Arabesque Labs design system: a Tailwind v4 theme on the --al-* tokens. Generated: don't edit.
   Use: @import "tailwindcss"; @import "./tokens.css"; @import "./tailwind-theme.css"; */
@theme inline {
  --spacing: 0.25rem;
${tw.join("\n")}
}
`);

// ---- tokens.json (flat) ------------------------------------------------------------------

const flat = {};
for (const t of all) {
  const entry = { value: resolve(t.value) };
  for (const [m, v] of Object.entries(t.modes)) entry[m] = resolve(v, m);
  flat[cssName(t)] = entry;
}
write("dist/tokens.json", `${JSON.stringify(flat, null, 2)}\n`);

// ---- arabesque.css: everything, in cascade layers ----------------------------------------

const layer = (name, file) => `@layer ${name} {\n/* ${file} */\n${read(file)}\n}\n`;
const components = readdirSync(join(root, "css/components")).filter((f) => f.endsWith(".css")).sort();
const bundle = [
  "/* Arabesque Labs design system. Generated by scripts/build.mjs: don't edit; change tokens/ and css/. */",
  "@layer al.tokens, al.base, al.layout, al.components, al.utilities;",
  `@layer al.tokens {\n${tokensCss}\n}`,
  layer("al.base", "css/base.css"),
  layer("al.layout", "css/layout.css"),
  ...components.map((f) => layer("al.components", `css/components/${f}`)),
  layer("al.utilities", "css/utilities.css"),
].join("\n");
write("dist/arabesque.css", bundle);

// ---- icons.svg: one sprite ---------------------------------------------------------------

const icons = readdirSync(join(root, "icons")).filter((f) => f.endsWith(".svg")).sort();
const symbols = icons.map((f) => {
  const svg = read(`icons/${f}`);
  const inner = svg.replace(/^[\s\S]*?<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "");
  return `  <symbol id="al-icon-${f.replace(/\.svg$/, "")}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.5" stroke-linecap="square" stroke-linejoin="miter">${inner}</symbol>`;
});
write("dist/icons.svg", `<svg xmlns="http://www.w3.org/2000/svg">\n${symbols.join("\n")}\n</svg>\n`);

// ---- contrast ----------------------------------------------------------------------------

/** A colour as linear sRGB and alpha: oklch(), hex. */
function parse(v) {
  v = String(v).trim();
  let m = /^#([0-9a-f]{6})$/i.exec(v);
  if (m) {
    const n = parseInt(m[1], 16);
    return { rgb: [(n >> 16) & 255, (n >> 8) & 255, n & 255].map((x) => dec(x / 255)), a: 1 };
  }
  m = /^oklch\(\s*([\d.]+)%\s+([\d.]+)\s+([\d.]+)(?:\s*\/\s*([\d.]+))?\s*\)$/.exec(v);
  if (!m) throw new Error(`can't read colour ${v}`);
  const [L, C, H] = [Number(m[1]) / 100, Number(m[2]), Number(m[3])];
  const h = (H * Math.PI) / 180;
  const a = C * Math.cos(h);
  const b = C * Math.sin(h);
  const l = (L + 0.3963377774 * a + 0.2158037573 * b) ** 3;
  const mm = (L - 0.1055613458 * a - 0.0638541728 * b) ** 3;
  const s = (L - 0.0894841775 * a - 1.291485548 * b) ** 3;
  const rgb = [
    4.0767416621 * l - 3.3077115913 * mm + 0.2309699292 * s,
    -1.2684380046 * l + 2.6097574011 * mm - 0.3413193965 * s,
    -0.0041960863 * l - 0.7034186147 * mm + 1.707614701 * s,
  ].map((x) => Math.min(1, Math.max(0, x)));
  return { rgb, a: m[4] === undefined ? 1 : Number(m[4]) };
}
function enc(x) { return x <= 0.0031308 ? 12.92 * x : 1.055 * x ** (1 / 2.4) - 0.055; }
function dec(x) { return x <= 0.04045 ? x / 12.92 : ((x + 0.055) / 1.055) ** 2.4; }
/** A translucent colour over an opaque one, blended as browsers do (in sRGB). */
const over = (top, under) => ({ rgb: top.rgb.map((x, i) => dec(enc(x) * top.a + enc(under.rgb[i]) * (1 - top.a))), a: 1 });
const lum = ({ rgb: [r, g, b] }) => 0.2126 * r + 0.7152 * g + 0.0722 * b;
const ratio = (x, y) => { const [hi, lo] = [lum(x), lum(y)].sort((p, q) => q - p); return (hi + 0.05) / (lo + 0.05); };

/** What sits on what, and the minimum it must reach: 4.5 for text, 3 for UI and graphics. */
const PAIRS = [
  ...["bg", "surface", "surface-sunk"].flatMap((g) => [["text", g, 4.5], ["text-muted", g, 4.5]]),
  ["accent", "bg", 4.5], ["accent", "surface", 4.5], ["on-accent", "accent", 4.5],
  ["text", "accent-wash", 4.5],
  ...["danger", "warning", "success", "info"].flatMap((s) => [[s, "bg", 4.5], [s, "surface", 4.5], [s, `${s}-wash`, 4.5], ["text", `${s}-wash`, 4.5]]),
  ["on-inverse", "inverse", 4.5],
  ["control", "bg", 3], ["control", "surface", 3], ["focus", "bg", 3], ["focus", "surface", 3],
  ...[1, 2, 3, 4].map((n) => [`chart-${n}`, "surface", 3]),
  ...["teal", "green", "yellow", "orange", "pink", "purple", "blue", "cyan"].map((n) => [`tint.${n}.ink`, `tint.${n}.bg`, 4.5]),
];
const color = (name, mode) => resolve(byPath.get(`semantic.color.${name}`).modes[mode] ?? byPath.get(`semantic.color.${name}`).value, mode);
let failed = 0;
const rows = [];
for (const mode of ["light", "dark"]) {
  const m = mode === "light" ? undefined : "dark";
  // A translucent ground (a wash) may sit on the page or on a surface: the
  // worse of the two is what counts.
  const underlays = [parse(color("bg", m)), parse(color("surface", m))];
  for (const [fg, bg, min] of PAIRS) {
    const r = Math.min(...underlays.map((under) => {
      const ground = over(parse(color(bg, m)), under);
      return ratio(over(parse(color(fg, m)), ground), ground);
    }));
    const ok = r >= min;
    if (!ok) failed += 1;
    rows.push(`| ${mode} | ${fg} | ${bg} | ${r.toFixed(2)} | ${min} | ${ok ? "pass" : "**FAIL**"} |`);
  }
}
write("docs/contrast.md", `# Contrast

Generated by \`scripts/build.mjs\`: every pair the system relies on, in both
themes, measured with the WCAG 2 contrast formula. Translucent colours are
blended over their ground in sRGB, as browsers do; a translucent ground is
measured on both the page and the surface, and the worse counts.
Text needs 4.5:1; controls, focus and chart marks need 3:1 (WCAG 1.4.11).
Hairlines (\`line\`, \`line-strong\`) and the pattern are decorative, and not
listed.

| Theme | Foreground | Background | Ratio | Minimum | Result |
|---|---|---|---|---|---|
${rows.join("\n")}
`);

console.log(`tokens: ${all.length}; components: ${components.length}; icons: ${icons.length}; contrast pairs: ${rows.length}, ${failed} failing`);
if (failed) process.exit(1);
