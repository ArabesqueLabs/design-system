#!/usr/bin/env node
// Builds the React layer, its examples and the homepage template (needs
// npm install: esbuild, TypeScript, React):
//
//   dist/react/index.js, *.d.ts     the components (react/src), for apps; React and the
//                                   helpers (js/) stay imports, so the helpers find
//                                   ../dist/icons.svg from where they are
//   examples/build/examples.js      the examples' one script: React and the components
//   examples/*.html                 a page per component, and the gallery: rendered in
//                                   the browser (they're demos, and need it anyway); the
//                                   build renders them too, to check their Arabic
//   templates/home.html, ar/home.html   rendered from templates/react/home.tsx: static,
//                                   wired by the helpers, no React in the page
//
// Every generated file sits at the same depth as its source, so ../../js/
// means js/ from both. It fails if an example's sentence has no Arabic.

import { build } from "esbuild";
import { execFileSync } from "node:child_process";
import { mkdirSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const at = (p) => join(root, p);
const write = (p, s) => { mkdirSync(dirname(at(p)), { recursive: true }); writeFileSync(at(p), s); };

/** The helpers stay imports, as written (../../js/pattern.js). */
const helpers = {
  name: "helpers",
  setup(b) {
    b.onResolve({ filter: /^\.\.\/\.\.\/js\/[\w-]+\.js$/ }, (a) => ({ path: a.path, external: true }));
  },
};
const common = { bundle: true, format: "esm", target: "es2022", jsx: "automatic", logLevel: "warning", absWorkingDir: root };

// ---- dist/react ------------------------------------------------------------------------------

rmSync(at("dist/react"), { recursive: true, force: true });
await build({
  ...common,
  entryPoints: ["react/src/index.ts"],
  outfile: "dist/react/index.js",
  platform: "neutral",
  external: ["react", "react-dom", "react/jsx-runtime"],
  plugins: [helpers],
  banner: { js: "/* Arabesque Labs design system: React components. Generated by scripts/build-react.mjs from react/src: don't edit. */" },
});
execFileSync(at("node_modules/.bin/tsc"), ["-p", at("react/tsconfig.json")], { stdio: "inherit" });
// The examples and the template are type-checked too (esbuild only strips types).
execFileSync(at("node_modules/.bin/tsc"), ["-p", at("examples/tsconfig.json")], { stdio: "inherit" });

// ---- examples/build --------------------------------------------------------------------------

await build({
  ...common,
  entryPoints: ["examples/src/client.tsx"],
  outfile: "examples/build/examples.js",
  platform: "browser",
  minify: true,
  define: { "process.env.NODE_ENV": '"production"' },
  plugins: [helpers],
});

// ---- render: the example pages and the templates ---------------------------------------------

// Bundled for Node, helpers and all (nothing runs that needs a browser), into
// node_modules so it finds React there.
const renderer = at("node_modules/.cache/arabesque/render.mjs");
await build({
  ...common,
  entryPoints: ["examples/src/render.tsx"],
  outfile: renderer,
  platform: "node",
  external: ["react", "react-dom"],
  // No storage on the server: js/keys.js's read of it (in a try) fails quietly,
  // without Node's warning about its own experimental localStorage.
  define: { "process.env.NODE_ENV": '"production"', localStorage: "undefined" },
});
const { render } = await import(`${pathToFileURL(renderer).href}?${Date.now()}`);
const { pages, templates, missing } = render();
if (missing.length) {
  console.error(`No Arabic for these (add them to examples/src/ar.ts):\n${missing.map((s) => `  ${JSON.stringify(s)}`).join("\n")}`);
  process.exit(1);
}

const esc = (s) => String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
const THEME = `<script>try { const t = localStorage.getItem("al-theme"); if (t === "light" || t === "dark") document.documentElement.dataset.theme = t; } catch {}</script>`;

// Pages that are gone are removed: examples/ holds only what's generated, and examples.css.
for (const f of readdirSync(at("examples"))) if (f.endsWith(".html")) rmSync(at(`examples/${f}`));
for (const p of pages) {
  write(p.file, `<!doctype html>
<html lang="${p.lang}" dir="${p.lang === "ar" ? "rtl" : "ltr"}">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>${esc(p.title)}</title>${p.description ? `\n  <meta name="description" content="${esc(p.description)}">` : ""}
  <!-- Generated by scripts/build-react.mjs from examples/src: don't edit. -->
  ${THEME}
  <link rel="icon" href="../assets/brand/star.svg" type="image/svg+xml">
  <link rel="stylesheet" href="../fonts/fonts.css">
  <link rel="stylesheet" href="../dist/arabesque.css">
  <link rel="stylesheet" href="examples.css">
  <script type="module" src="build/examples.js"></script>
</head>
<body data-example="${p.example}">
<div id="root"></div>
</body>
</html>
`);
}

for (const p of templates) {
  const up = p.lang === "ar" ? "../../" : "../";
  write(p.file, `<!doctype html>
<html lang="${p.lang}" dir="${p.lang === "ar" ? "rtl" : "ltr"}">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>${esc(p.title)}</title>
  <meta name="description" content="${esc(p.description)}">
  <!-- Generated by scripts/build-react.mjs from templates/react/home.tsx: change that, not this. -->
  <!-- The saved theme, before first paint. -->
  ${THEME}
  <link rel="icon" href="${up}assets/brand/star.svg" type="image/svg+xml">
  <link rel="stylesheet" href="${up}fonts/fonts.css">
  <link rel="stylesheet" href="${up}dist/arabesque.css">
  <link rel="stylesheet" href="${up}templates/home.css">
</head>
<body>
${p.body}
<script type="module">
  import { drawHero, initConstruction } from "${up}js/pattern.js";
  import { initSiteHeaders } from "${up}js/site-header.js";
  import { currentTheme, setTheme } from "${up}js/theme.js";

  for (const el of document.querySelectorAll("[data-pattern-hero]")) drawHero(el, { animate: true });
  initConstruction();
  initSiteHeaders();

  const theme = document.querySelector("[data-theme-toggle]");
  const label = () => theme.setAttribute("aria-label", currentTheme() === "dark" ? theme.dataset.labelLight : theme.dataset.labelDark);
  theme.addEventListener("click", () => { setTheme(currentTheme() === "dark" ? "light" : "dark"); label(); });
  label();
</script>
</body>
</html>
`);
}

console.log(`react: dist/react; examples: ${pages.length - 1} pages and the gallery; templates: ${templates.map((t) => t.file).join(", ")}`);
